func TestCalculatePasswordVerifier(t *testing.T) {
	username := "LF2BGFQIFQ3HZ1ZF"
	password := "MVRVMUJFWRA0IBVK"
	salt := []byte{
		0x6F, 0xEF, 0xAB, 0xE6, 0x0F, 0xDA, 0x4A, 0x15,
		0xCC, 0xA3, 0xD2, 0xF2, 0xFE, 0xFB, 0xE8, 0x40,
		0x89, 0x92, 0xA0, 0xAC, 0x91, 0x5D, 0xED, 0xAF,
		0x3D, 0xBB, 0x5D, 0x92, 0x8E, 0xD2, 0xE5, 0xAF,
	}
	expected := []byte{
		0xFF, 0x33, 0xEB, 0x01, 0x42, 0x9D, 0xB7, 0xB3,
		0x25, 0xB5, 0xAC, 0x0C, 0xC4, 0x13, 0x9A, 0xA9,
		0x79, 0x3F, 0xCC, 0x90, 0x26, 0x8F, 0xD2, 0x69,
		0x0A, 0x8D, 0x93, 0x0A, 0x3B, 0x15, 0xB4, 0x21,
	}
	verifier := calculatePasswordVerifier(username, password, salt)
	if bytes.Compare(expected, verifier) != 0 {
		t.Fatalf("Verifier calculated incorrectly, expected %v but was %v", expected, verifier)
	}

}

