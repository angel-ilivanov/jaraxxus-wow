func TestEncryptHeader(t *testing.T) {
	sessionKey := []byte{
		0xde, 0xe8, 0xa4, 0x4c, 0xdb, 0xa7, 0xba, 0xec,
		0x75, 0x76, 0x8b, 0x97, 0x88, 0x98, 0x5b, 0xe4,
		0xa3, 0x36, 0x09, 0x18, 0x88, 0x80, 0x49, 0xa1,
		0xd5, 0x17, 0xe5, 0xc7, 0xb6, 0x18, 0xf1, 0x43,
		0xae, 0xcd, 0x1f, 0x2b, 0x7b, 0xce, 0x3f, 0x40,
	}
	header := []byte{
		0xdb, 0x26, 0x25, 0xe3, 0x22, 0x19, 0x9f, 0x71,
		0x5f, 0x67, 0xf8, 0xe6, 0xdc, 0x54, 0xfe, 0x72,
		0x18, 0x44, 0xee, 0xbc, 0x89, 0xf4, 0x8a, 0x13,
		0x4d, 0x7c, 0x87, 0x12, 0x68, 0xcb, 0x5d, 0x2b,
		0x7a, 0x0f, 0x73, 0xcf, 0x87, 0xe8, 0x23, 0x51,
		0x72, 0x6e, 0xf0, 0x13, 0xd6, 0xcb, 0x8d, 0x4c,
		0xba, 0xde,
	}
	expectedEncrypt := []byte{
		0x41, 0x1a, 0xfe, 0x3a, 0x8b, 0x2c, 0x25, 0xb1,
		0x8d, 0xaf, 0xc2, 0x3d, 0xe3, 0x03, 0xcc, 0xbf,
		0x7a, 0x3a, 0x53, 0xd5, 0x14, 0x36, 0xda, 0xfe,
		0x2c, 0x59, 0x9c, 0xdd, 0xeb, 0xfd, 0x40, 0xf7,
		0x46, 0x76, 0xb1, 0x30, 0x6f, 0x78, 0xf9, 0xaf,
		0xf7, 0x66, 0x72, 0xcf, 0xe2, 0x86, 0x17, 0x68,
		0x2d, 0x46,
	}
	encryption := HeaderCipher{}
	err := encryption.Init(sessionKey)
	if err != nil {
		t.Fatalf("failed to initialize encryption ciphers: %v", err)
	}
	err = encryption.EncryptHeader(header)
	if err != nil {
		t.Fatalf("failed to encrypt header: %v", err)
	}
	if bytes.Compare(header, expectedEncrypt) != 0 {
		t.Fatalf("incorrectly encrypted header, expected %v but got %v", expectedEncrypt, header)
	}
}

