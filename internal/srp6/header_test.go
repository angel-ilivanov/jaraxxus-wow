func TestCreateTrafficKey(t *testing.T) {
	sessionKey := []byte{
		0x3b, 0x19, 0xea, 0x78, 0x21, 0x3d, 0x3b, 0xc6,
		0xf5, 0x6a, 0x7d, 0xa2, 0xcd, 0x1d, 0xc1, 0x13,
		0x4a, 0x47, 0x29, 0x65, 0x33, 0x6a, 0xa8, 0xb1,
		0x17, 0xc6, 0xd0, 0xb9, 0xdc, 0x40, 0x50, 0x33,
		0x21, 0x8d, 0x75, 0xbf, 0x07, 0x0b, 0xca, 0xae,
	}

	key := []byte{
		0xb4, 0x92, 0x84, 0x8c, 0x9e, 0xff, 0x1b, 0x52,
		0x17, 0xf8, 0xd3, 0x66, 0x2a, 0xea, 0x1b, 0x30,
	}

	expected := []byte{
		0xc3, 0x30, 0xa6, 0xcf, 0xfe, 0x66, 0xd0, 0x0a,
		0xf8, 0xeb, 0x04, 0x31, 0x82, 0x88, 0x20, 0x31,
		0x1c, 0xe0, 0xa1, 0x58,
	}
	hMacKey := createTrafficKey(sessionKey, key)
	if bytes.Compare(expected, hMacKey) != 0 {
		t.Fatalf("incorrect hmac key calculation, expected %v but got %v", expected, hMacKey)
	}
}
